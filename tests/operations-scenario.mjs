import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
export async function operationsScenario(f){
  const a=f.client(),e=f.client(),other=f.client();for(const [c,name] of [[a,'ADMIN'],[e,'001'],[other,'002']])assert.equal((await c.login(name)).status,200);
  const post=(c,path,body)=>c.call('/api/operations/'+path,{requestKey:randomUUID(),...body});
  const ok=async promise=>{const r=await promise;assert.equal(r.status,200,JSON.stringify(r.data));return r.data;};
  const get=(c,path)=>ok(c.call('/api/operations/'+path));
  const firstItem={drawing:'TEST-001',name:'검증용 부품',model:'TEST',kind:'part',unit:'EA',supplier:'검증업체',source:'합성 시험 기준',criteria:'치수 10±0.1 mm, 시료 5개',warnings:'실제 회사 자료 아님',active:true,version:0,reason:'시험 품목'};
  assert.equal((await post(e,'items',firstItem)).status,403);
  const {id:itemId}=await ok(post(a,'items',firstItem));
  assert.equal((await e.call('/api/operations/materials')).status,403);
  assert.equal((await e.call('/api/operations/quality/history')).status,403);
  await ok(post(a,'access',{userId:'ue2',production_review:true,materials:true,quality:false,version:0,reason:'검증 담당'}));
  const p={itemId,taskId:'t1',lotCode:'RUN-01',process:'Frame',good:12,bad:1,note:'시험',requestKey:randomUUID()};
  const run=await ok(post(e,'production',p));assert.deepEqual(await ok(post(e,'production',p)),run);
  assert.equal((await post(e,'production',{...p,good:99})).status,409);
  assert.equal((await get(e,'production')).rows.length,1);
  assert.equal((await post(e,'production/review',{id:run.id,version:1,status:'approved',reason:'무권한'})).status,403);
  assert.equal((await a.call('/api/admin/production',{id:run.id,version:1,taskId:'t1',good:99,bad:0,reason:'우회'})).status,409);
  const reviewed=await ok(post(other,'production/review',{id:run.id,version:1,status:'approved',reason:'수량 확인'}));
  assert.ok(reviewed.lotId);assert.equal((await get(other,'materials')).rows[0].status,'pending');
  assert.equal((await post(e,'production/correct',{...p,requestKey:randomUUID(),id:run.id,version:2,reason:'승인 이후'})).status,409);
  assert.equal((await post(other,'production/review',{id:run.id,version:1,status:'approved',reason:'중복 승인'})).status,409);
  assert.equal((await a.call('/api/admin/test-data/preview',{kind:'production',ids:[run.id],reason:'테스트 정리'})).status,409);
  const move={id:reviewed.lotId,version:1,kind:'issue',quantity:1,reason:'검사 전 출고'};
  assert.equal((await post(other,'materials/move',move)).status,409);
  const inspection={id:reviewed.lotId,version:1,stage:'process',sample:5,failed:0,decision:'pass',criteria:'10±0.1 mm',measurements:'10.00, 10.01, 10.00, 9.99, 10.02 mm',criteriaConfirmed:true,reason:'표준 확인'};
  assert.equal((await post(other,'quality/inspect',inspection)).status,403);
  assert.equal((await post(a,'quality/inspect',{...inspection,criteriaConfirmed:false})).status,400);
  assert.equal((await post(a,'quality/inspect',{...inspection,failed:1})).status,400);
  await ok(post(a,'quality/inspect',{...inspection,failed:1,decision:'fail'}));
  assert.equal((await post(other,'materials/move',{...move,version:2})).status,409);
  assert.equal((await post(a,'quality/inspect',inspection)).status,409);
  await ok(post(a,'quality/inspect',{...inspection,version:2,reason:'선별 후 재검사'}));
  assert.equal((await post(other,'materials/move',{...move,version:3,quantity:13})).status,409);
  const issue={...move,version:3,quantity:4,reason:'생산 투입',requestKey:randomUUID()};
  await ok(post(other,'materials/move',issue));await ok(post(other,'materials/move',issue));
  let current=(await get(other,'materials')).rows[0];assert.equal(current.balance,8);assert.equal(current.version,4);
  await ok(post(other,'materials/move',{...move,version:4,kind:'adjust',quantity:2,reason:'실사 차이 확인'}));
  current=(await get(other,'materials')).rows[0];assert.equal(current.balance,10);assert.equal(current.status,'pending');
  const log=(await get(other,'materials/history')).rows;assert.equal(log.reduce((sum,m)=>sum+m.quantity,0),10);
  const inspections=(await get(a,'quality/history')).rows;assert.equal(inspections.length,2);assert.ok(inspections.every(q=>q.item_snapshot.includes('TEST-001')));
  const receive={itemId,lotCode:'RCV-01',supplier:'검증업체',quantity:20,reason:'거래명세 T01',requestKey:randomUUID()};
  const received=await ok(post(other,'materials/receive',receive));assert.deepEqual(await ok(post(other,'materials/receive',receive)),received);
  assert.equal((await post(other,'materials/receive',{...receive,requestKey:randomUUID()})).status,409);
  const denied=await ok(post(e,'production',{...p,lotCode:'RUN-02',requestKey:randomUUID()}));
  await ok(post(other,'production/review',{id:denied.id,version:1,status:'rejected',reason:'수량 재확인'}));
  await ok(post(e,'production/correct',{...p,id:denied.id,version:2,good:10,lotCode:'RUN-02',reason:'실측 정정',requestKey:randomUUID()}));
  assert.equal((await get(e,'production')).rows.find(r=>r.production_id===denied.id).status,'pending');
  await ok(post(a,'access',{userId:'ue2',production_review:false,materials:false,quality:false,version:1,reason:'담당 해제'}));
  assert.equal((await other.call('/api/operations/materials')).status,403);
  assert.equal((await post(other,'materials/receive',receive)).status,403,'권한 해제 후 재시도도 거부');
  assert.equal((await get(other,'production')).rows.length,0);
  return {itemId,runId:run.id,lotId:reviewed.lotId};
}
